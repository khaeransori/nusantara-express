// Dump every sprite to JSON so tools/sheet.py can render a quick review sheet.
import fs from 'node:fs';
import vm from 'node:vm';
const ctx = { console };
vm.createContext(ctx);
for (const f of ['../src/assets/px.js', '../src/assets/sprites.js']) vm.runInContext(fs.readFileSync(new URL(f, import.meta.url), 'utf8'), ctx);
const NX = vm.runInContext('NX', ctx);
const out = [];
const add = (name, s) => out.push({ name, w: s.w, h: s.h, d: s.d.join('') });
const S = NX.SPR;
add('oyen', S.oyen); add('oyenBlink', S.oyenBlink);
for (const k of ['uniRani', 'masBayu', 'bliMade', 'daengIcal', 'mamaYosina', 'ayukIna', 'mpokSiti', 'acilAisyah']) add(k, S[k]);
S.coinSpin.forEach((c, i) => add('coin' + i, c)); add('rainCloud', S.rainCloud); add('cloudWhite', S.cloudWhite); add('splash', S.splash);
add('capung0', S.capung[0]); add('capung1', S.capung[1]); add('pinisi', S.pinisi);
for (const [k, v] of Object.entries(S.food)) add(k, v);
for (const [k, v] of Object.entries(S.houses)) add(k, v);
for (const [k, v] of Object.entries(S.icons)) add(k, v);
add('miniPlane', S.miniPlane); add('mapPin', S.mapPin);
fs.writeFileSync(process.argv[2] || '/tmp/sprites.json', JSON.stringify({ pal: NX.PAL, sprites: out }));
console.log(out.map(o => `${o.name} ${o.w}x${o.h}`).join('\n'));
